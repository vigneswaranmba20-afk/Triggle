'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const d=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/textbook-exercises/g9-ch1-ex1-2-q1-i.json'),'utf8'));
assert.equal(d.questions.length,1);
const q=d.questions[0];
assert.equal(q.id,'g9-ch1-ex1.2-q1-i');
assert.equal(q.stemEnglish,'Find the cardinal number of the following sets.');
assert.equal(q.promptEnglish,'(i) M = {p, q, r, s, t, u}');
assert.equal(q.answerEnglish,'n(M) = 6');
const members=q.promptEnglish.match(/\{([^}]+)\}/)[1].split(',').map(x=>x.trim());
assert.equal(new Set(members).size,6);
assert.equal(members.length,6);
assert.equal(q.stepsEnglish.length,3);
assert.equal(q.translation.tamil,'pending');
assert.equal(q.review.publication,'draft');
assert.equal(d.source.visualChecked,false);
