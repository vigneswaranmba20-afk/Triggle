'use strict';
// Reader controls do not appear or disappear in response to a touch/release.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=p=>fs.readFileSync('site/'+p,'utf8');
const js=read('assets/quiet-reader.js'),css=read('assets/quiet-reader.css');
const html=read('index.html'),sw=read('service-worker.js');
new vm.Script(js,{filename:'quiet-reader.js'});
assert.doesNotMatch(js,/pointerdown|pointerup|pointercancel|setTimeout|hideLater|RELEASE_GRACE/,'No touch or timer based hiding');
assert.match(js,/reader-options-visible',active/,'Controls always visible');
assert.match(js,/reader-long-question/,'Long questions remain fully readable');
assert.match(js,/triggle:lessonchange/,'Reset for each question');
assert.match(js,/\.inert=false/,'No controls are made inert');
assert.match(css,/#figureBtn:not\(\[hidden\]\)\{[\s\S]*display:inline-flex!important/);
assert.match(css,/#inlineFigure:not\(\[hidden\]\)\{[\s\S]*display:block!important/);
assert.match(css,/#questionNavDock\{[\s\S]*visibility:visible!important/);
assert.doesNotMatch(css,/reader-peek:not\(\.reader-options-visible\)/);
assert.match(html,/quiet-reader\.css\?v=static-reader-1/);
assert.match(html,/quiet-reader\.js\?v=static-reader-1/);
assert.doesNotMatch(html,/focus-navigation\.js|id="focusNavToggle"/);
assert.doesNotMatch(html,/class="reference-line"|class="bottom-extras"/);
assert.match(sw,/quiet-reader\.js/);assert.match(sw,/quiet-reader\.css/);
console.log('PASS permanent reader, no touch hide, clutter footer gone');
