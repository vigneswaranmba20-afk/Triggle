'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..'),{loadRuntime,validateBatch}=require('./curriculum_bulk.cjs');
const manifest=require('../../docs/curriculum/grade-10/batches/g10-ch2-ex2-2.json');
const ids=manifest.records.map(r=>r.id);
assert.deepEqual(ids,['1','2','3','4','5','6','7','9'].map(n=>'c10-2-ex2-2-q'+n));
assert.equal(manifest.inventory.exercises[0].complete,false,'Unresolved Q8 prevents a complete-exercise claim');
assert.equal(manifest.inventory.exercises[0].questions.length,9);
const blocked=manifest.inventory.exercises[0].questions.find(q=>q.number==='8');
assert.equal(blocked.status,'blocked');
assert(!ids.includes('c10-2-ex2-2-q8'));
assert.equal(manifest.tamilStatus,'pending');
const report=validateBatch(manifest,{integrated:true});
assert.equal(report.passed,true,report.errors.join('\n'));
assert.equal(report.metrics.mathematicallyVerifiedRecords,8);
assert.equal(report.coverage.blocked.length,1);
assert.equal(report.coverage.chapterComplete,false);
const runtime=loadRuntime();
const chapter=runtime.curriculum.grades.find(g=>g.grade===10).chapters.find(ch=>Number(ch.number)===2);
const entries=runtime.classes[10].items.filter(x=>ids.includes(x.id));
assert.equal(entries.length,8);
assert(ids.every(id=>chapter.textbookQuestionIds.includes(id)));
assert(!runtime.classes[10].items.some(x=>x.id==='c10-2-ex2-2-q8'));
const html=fs.readFileSync(path.join(root,'site/index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'site/service-worker.js'),'utf8');
assert(html.includes('g10-ch2-ex2-2-en.js'));
assert(sw.includes('g10-ch2-ex2-2-en.js'));
assert(sw.includes('matrix-concepts-bulk-g10ex22'));
console.log('PASS Grade 10 Exercise 2.2 release: eight source-checked records, Q8 quarantined, navigation/offline/cache ready, no false complete claim');
