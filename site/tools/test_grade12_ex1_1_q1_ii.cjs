const A=[[2,3,1],[3,4,1],[3,7,2]];
const expectedAdj=[[1,1,-1],[-3,1,1],[9,-5,-1]];
const det2=(a,b,c,d)=>a*d-b*c;
const cof=A.map((row,i)=>row.map((_,j)=>{
 const minor=A.filter((_,r)=>r!==i).map(r=>r.filter((_,c)=>c!==j));
 return ((i+j)%2?-1:1)*det2(minor[0][0],minor[0][1],minor[1][0],minor[1][1]);
}));
const transpose=m=>m[0].map((_,i)=>m.map(row=>row[i]));
const multiply=(x,y)=>x.map(row=>y[0].map((_,j)=>row.reduce((sum,v,k)=>sum+v*y[k][j],0)));
const determinant=A[0].reduce((sum,x,j)=>sum+x*cof[0][j],0);
assert.deepEqual(cof,[[1,-3,9],[1,1,-5],[-1,1,-1]]);
assert.deepEqual(transpose(cof),expectedAdj);
assert.equal(determinant,2);
const identity=[[2,0,0],[0,2,0],[0,0,2]];
assert.deepEqual(multiply(A,expectedAdj),identity);
assert.deepEqual(multiply(expectedAdj,A),identity);
