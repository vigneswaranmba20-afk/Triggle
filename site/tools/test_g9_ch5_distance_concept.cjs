'use strict';
// Grade 9 Coordinate Geometry: bilingual concept + approved media release gates.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const file=path.join(root,'data/g9-ch5-distance-concept.js');
const script=fs.readFileSync(file,'utf8');
const ctx={window:{}};
vm.runInNewContext(script,ctx,{filename:'g9-ch5-distance-concept.js'});
const lesson=ctx.window.TRIGGLE_G9_CH5_PATH;
assert.equal(lesson.chapterId,'g9-ch5');
assert.equal(lesson.stages.length,1,'Only the published §5.3 concept is released, not the entire chapter');
assert.equal(lesson.stages[0].section,'5.3');
assert.match(lesson.tamilStatus,/pending/);
const stage=lesson.stages[0];
assert.equal(stage.id,'g9-ch5-distance-formula');
assert.equal(stage.visual.kind,'g9-distance-grid');
for(const k of ['title','idea','example','question','hint','why']){
  assert.ok(stage[k]?.en?.length>10 && stage[k]?.ta?.length>10,'English and Tamil: '+k);
}
assert.equal(stage.choices.length,3);
assert.equal(stage.correct,0);
assert.match(stage.math.latex,/\\sqrt\{\(x_2-x_1\)\^2\+\(y_2-y_1\)\^2\}/,'Radical must span both squared differences');
assert.match(stage.exampleMath.latex,/\\sqrt\{\(4-1\)\^2\+\(6-2\)\^2\}/,'Worked radical must cover both terms');
assert.match(stage.whyMath.latex,/\\sqrt\{36\+64\}/,'Practice radical must cover the whole sum');
assert.equal(Math.hypot(4-1,6-2),5,'Example Pythagoras arithmetic');
assert.equal(Math.hypot(6,8),10,'Practice Pythagoras arithmetic');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const hub=fs.readFileSync(path.join(root,'assets/chapter-hub.js'),'utf8');
const css=fs.readFileSync(path.join(root,'assets/g9-concept-theme.css'),'utf8');
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
assert.ok(html.includes('data/g9-ch5-distance-concept.js'),'Concept script loaded');
assert.ok(html.indexOf('data/g9-ch5-distance-concept.js')<html.indexOf('assets/chapter-hub.js'),'Data must precede hub');
assert.ok(sw.includes("CORE.push('./data/g9-ch5-distance-concept.js')"),'Offline precache path');
assert.ok(hub.includes("chapter.id==='g9-ch5'"),'Registered in chapter hub');
assert.ok(hub.includes('TRIGGLE_G9_CH5_PATH'),'Stage registry bound');
assert.ok(hub.includes('g9-distance-grid'),'Mathematically labelled SVG drawing');
assert.ok(hub.includes("g9-ch5-distance-formula"),'Native lesson video support');
assert.ok(css.includes('.g9-distance-lab'),'Mobile visual styling');
const media=path.join(root,'videos/triggle-g9-distance-formula-en.mp4');
assert.equal(stage.video.src,'https://pub-ed71b86e97a64b428086e292b26fb7a2.r2.dev/trace-videos/g9-ch5-distance-formula/8ada907f59bf11788bad196fc8e3ec876de4bc5d98caef53fa50368d78277323.mp4');
assert.equal(stage.video.provider,'cloudflare-r2');
assert.equal(lesson.approvedMedia.status,'hosted-on-cloudflare-r2');
assert.equal(stage.video.durationSeconds,75.6);
const stat=fs.statSync(media);
assert.equal(stat.size,2031309,'Approved MP4 source byte count');
const hash=crypto.createHash('sha256').update(fs.readFileSync(media)).digest('hex');
assert.equal(hash,'8ada907f59bf11788bad196fc8e3ec876de4bc5d98caef53fa50368d78277323','Release media is the exact corrected video');
assert.ok(!/g1[12]-/.test(stage.id),'Do not publish Grade 11 or Grade 12 lesson');
console.log('PASS G9 Ch5 distance concept: bilingual content, math, radical reach, nav, offline, and reviewed video SHA-256.');
