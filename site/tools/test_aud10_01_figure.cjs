'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const load=p=>fs.readFileSync(path.resolve(__dirname,'..',p),'utf8');
const svg=load('assets/grade9-ch7/ex7-1-q6.svg');
const points=Object.fromEntries([...svg.matchAll(/<circle id="([ABCD])" cx="([\d.]+)" cy="([\d.]+)"/g)].map(m=>[m[1],[+m[2],+m[3]]]));
const {A,B,C,D}=points;
const sub=(a,b)=>a.map((x,i)=>x-b[i]);
const dot=(a,b)=>a.reduce((s,x,i)=>s+x*b[i],0);
const cross=(a,b)=>a[0]*b[1]-a[1]*b[0];
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-7, a+' != '+b);
const scale=6;
for(const [p,q,len] of [[A,B,20],[A,D,12],[B,D,16],[B,C,42],[C,A,34]])near(Math.hypot(...sub(p,q))/scale,len);
near(dot(sub(A,D),sub(B,D)),0);
const area=(a,b,c)=>Math.abs(cross(sub(b,a),sub(c,a)))/(2*scale*scale);
near(area(A,B,C),336);near(area(A,B,D),96);near(area(A,B,C)-area(A,B,D),240);
near(area(A,B,D)+area(B,C,D)+area(C,A,D),area(A,B,C));
const marker=svg.match(/<path d="M([\d.]+),([\d.]+) L([\d.]+),([\d.]+) L([\d.]+),([\d.]+)"/);
assert.ok(marker);
const [P,Q,R]=[[+marker[1],+marker[2]],[+marker[3],+marker[4]],[+marker[5],+marker[6]]];
near(cross(sub(P,D),sub(A,D)),0);near(cross(sub(R,D),sub(B,D)),0);
near(dot(sub(P,Q),sub(R,Q)),0);
const mapping=load('assets/app.js').match(/'g9-ch7-ex7\.1-q6':\{[^\n]+/)[0];
assert.ok(mapping.includes('ex7-1-q6.svg')&&mapping.includes('altTa:')&&mapping.includes('captionTa:'));
assert.ok(load('service-worker.js').includes('./assets/grade9-ch7/ex7-1-q6.svg'));
console.log('PASS AUD10-01: exact five lengths, perpendicular legs and marker, interior shaded triangle, 240 cm², EN/TA figure mapping and cache.');
