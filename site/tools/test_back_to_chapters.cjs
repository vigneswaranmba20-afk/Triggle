'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const html=read('site/index.html');
const js=read('site/assets/app.js');
const css=read('site/assets/app.css');
const focus=read('site/assets/focus-navigation.js');
const sw=read('site/service-worker.js');
const nav=html.match(/<nav id="questionNavDock" class="page-controls" aria-label="Navigate questions" hidden>([\s\S]*?)<\/nav>/);
assert.ok(nav,'All three question actions must share a single landmark/navigation container');
const content=nav[1];
const prev=content.indexOf('id="previous"'),all=content.indexOf('id="allChaptersReturn"'),next=content.indexOf('id="next"');
assert.ok(prev>=0&&prev<all&&all<next,'Order must be Previous, Back to all chapters, Next');
assert.match(content,/<button type="button" id="allChaptersButton" class="all-chapters-button">[\s\S]*?data-i18n="backAllChapters"/);
assert.equal((html.match(/id="allChaptersButton"/g)||[]).length,1,'Do not duplicate the chapter button');
assert.equal((html.match(/id="previous"/g)||[]).length,1,'Do not leave any floating Previous button');
assert.equal((html.match(/id="next"/g)||[]).length,1,'Do not leave any floating Next button');
assert.match(html,/<\/div>\s*<nav id="questionNavDock"/,'Dock must be a sibling below the scrollable lesson container');
assert.match(js,/backAllChapters:'Back to all chapters'/);
assert.match(js,/backAllChapters:'அனைத்து அத்தியாயங்களுக்கும் திரும்பு'/);
assert.match(js,/\$\('allChaptersButton'\)\.onclick=\(\)=>changeGrade\(grade\)/);
assert.match(js,/function changeGrade\(g\)\{[\s\S]*?classIndex=true;/);
assert.match(js,/if\(classIndex\)u\.searchParams\.set\('browse','chapters'\)/);
assert.match(js,/\$\('questionNavDock'\)\.hidden=!showingQuestion/,'Do not show the dock on chapter directories');
assert.match(js,/body\.classList\.toggle\('textbook-reader',showingQuestion\)/,'All question pages share nonfloating reader mode');
assert.match(focus,/!document\.body\.classList\.contains\('textbook-reader'\)/,'Old auto-hiding floating chrome must not activate in textbook reader');
assert.match(css,/body\.textbook-reader \.crumb-link\{[^}]*min-height:46px/,'Readable breadcrumb target');
assert.match(css,/body\.textbook-reader \.page-controls\{[^}]*box-shadow:none/,'No floating overlay shadows');
assert.match(css,/body\.textbook-reader \.lesson-container\{[^}]*overflow-y:auto!important/,'Reading content owns scrolling');
assert.match(css,/body\.textbook-reader \.page-controls\{position:relative!important/,'The dock reserves layout space instead of covering solutions');
assert.match(css,/body\.textbook-reader \.class-dock,body\.textbook-reader #focusNavToggle\{display:none!important/,'No duplicate floating controls');
assert.match(css,/\.page-controls button:focus-visible/,'Keyboard focus is visible');
const cacheVersion=Number(sw.match(/triggle-shell-real-2025-v(\d+)/)?.[1]);
assert.ok(Number.isInteger(cacheVersion)&&cacheVersion>=42);
const hub=read('site/assets/chapter-hub.js'),hubCss=read('site/assets/chapter-hub.css');
assert.match(content,/class="nav-arrow" aria-hidden="true">←<\/span>/,'Return arrow is separate from the label');
assert.match(css,/--triggle-nav-font-size:16px/,'All reader buttons use 16px type');
assert.match(css,/grid-template-areas:"chapters chapters" "previous next"/,'Back takes the first mobile row; Previous/Next share the second row');
assert.match(css,/grid-area:previous/,'Previous has a stable grid cell');
assert.match(css,/grid-area:chapters/,'All chapters has a full-width row');
assert.match(css,/grid-area:next/,'Next has a stable grid cell');
assert.match(hub,/back:'Back to chapter',classBack:'Back to all chapters'/,'Chapter-level wording matches the question reader');
assert.match(js,/'Back to all exercises'/,'Exercise return wording is consistent');
assert.match(hubCss,/font-size:var\(--triggle-nav-font-size,16px\)/,'Chapter navigation uses the shared font size');
assert.match(js,/if\(!chapterOverview\)\{choices\.push\(/,'Chapter overview breadcrumb must keep class-only navigation');
assert.match(hub,/chapterNumber\+\(section\?/,'Chapter number is a compact identifier rather than a repeated heading');
assert.ok(!hub.includes("t.eyebrow+' · '+t.navigation+' · '+grade"),'Remove redundant chapter header metadata');
assert.match(hub,/breakdown\.className='hub-question-breakdown'/,'Compact bilingual section counts remain available');
assert.ok(hub.indexOf('menu.append(grid);root.append(menu);')<hub.indexOf('metadata.textContent=grade9Pilot'),
  'Show section choices before small textbook review note');
assert.match(css,/body\.chapter-overview-active \.class-dock\{display:none!important\}/,'Floating class dock must not obscure hub cards');
assert.match(css,/body\.chapter-overview-active \.app-shell\{height:100dvh!important/,'Chapter content fills viewport once grade dock is removed');
assert.match(hubCss,/\.chapter-hub \.hub-question-breakdown\{[\s\S]*?border:0/,'Replace large statistics callout with quiet compact text');
console.log('PASS: chapter and reader navigation share non-overlapping bilingual routes, with one title and immediate section choices.');
