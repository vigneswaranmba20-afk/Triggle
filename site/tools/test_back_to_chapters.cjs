'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const html=read('site/index.html');
const js=read('site/assets/app.js');
const css=read('site/assets/app.css');
const sw=read('site/service-worker.js');
assert.match(html,/<nav class="page-controls"[^>]*>[\s\S]*?<\/nav>\s*<div class="all-chapters-return" id="allChaptersReturn" hidden>/,'Back button must be directly below question pager');
assert.match(html,/<button type="button" id="allChaptersButton" class="all-chapters-button">[\s\S]*?data-i18n="backAllChapters"/,'Button must be accessible and localizable');
assert.match(js,/backAllChapters:'Back to all chapter options'/,'English translation');
assert.match(js,/backAllChapters:'அனைத்து அத்தியாயத் தேர்வுகளுக்கும் திரும்பு'/,'Tamil translation');
assert.match(js,/\$\('allChaptersButton'\)\.onclick=\(\)=>changeGrade\(grade\)/,'Action must return to chapter index for current class');
assert.match(js,/function changeGrade\(g\)\{[\s\S]*?classIndex=true;/,'Change grade must open chapter index');
assert.match(js,/if\(classIndex\)u\.searchParams\.set\('browse','chapters'\)/,'Chapter index should be restorable from URL');
assert.match(js,/\$\('allChaptersReturn'\)\.hidden=homeView\|\|classIndex\|\|!!chapterOverview/,'Do not show button outside question mode');
assert.match(css,/\.all-chapters-button\{[^}]*min-height:50px/,'Mobile-friendly touch target');
assert.match(css,/\.all-chapters-button:focus-visible/,'Visible keyboard focus');
const cacheVersion=Number(sw.match(/triggle-shell-real-2025-v(\d+)/)?.[1]);
assert.ok(Number.isInteger(cacheVersion)&&cacheVersion>=37,'Keep a versioned offline cache without pinning a stale release');
console.log('PASS: Back to all chapter options navigation (EN/TA, visibility, routing, accessibility and cache).');
