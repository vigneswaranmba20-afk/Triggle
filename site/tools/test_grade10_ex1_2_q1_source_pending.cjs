'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const file = path.join(__dirname, '../data/textbook-exercises/g10-ch1-ex1-2-q1-source-pending.json');
const draft = JSON.parse(fs.readFileSync(file, 'utf8'));
assert.equal(draft.grade, 10);
assert.equal(draft.exercise, '1.2');
assert.equal(draft.question, '1');
assert.equal(draft.subparts.length, 4);
assert.equal(new Set(draft.subparts.map(s => s.id)).size, 4);
const A = new Set(draft.sets.A);
const B = new Set(draft.sets.B);
const expected = [false, false, true, false];
draft.subparts.forEach((subpart, index) => {
  assert.equal(subpart.id, ['i','ii','iii','iv'][index]);
  const mathematicallyIsRelation = subpart.pairs.every(([x,y]) => A.has(x) && B.has(y));
  assert.equal(subpart.isRelation, mathematicallyIsRelation, subpart.id);
  assert.equal(subpart.isRelation, expected[index], subpart.id);
  assert.ok(subpart.stepsEnglish.length >= 3);
});
assert.equal(draft.source.english.exactQuestionVerified, false);
assert.equal(draft.source.english.pageImageVerified, false);
assert.equal(draft.review.englishExactQuestionVerified, false);
assert.equal(draft.review.tamilVerified, false);
assert.equal(draft.review.merged, false);
assert.equal(draft.review.deployed, false);
assert.equal(draft.review.liveVerified, false);
console.log('Grade 10 Exercise 1.2 Q1(i–iv) mathematical/source-pending checks passed');
