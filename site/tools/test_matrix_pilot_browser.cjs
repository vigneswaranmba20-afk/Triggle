'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright'),{server,launchOptions}=require('./dashboard_test_support.cjs');
(async()=>{const app=await server(),browser=await chromium.launch(launchOptions());
try{const page=await browser.newPage();await page.goto(app.base+'/matrix-pilot.html?mode=learn');
await page.waitForURL('**/index.html');
await page.locator('.discover-grade-grid [data-grade="9"]').waitFor({state:'visible'});
assert.deepEqual(await page.locator('.discover-grade-grid [data-grade]').evaluateAll(nodes=>nodes.map(n=>Number(n.dataset.grade))),[9,10]);
assert.equal(await page.locator('#lessonCard').isVisible(),false,'Retired Q8 solution cannot render publicly');
await page.goto(app.base+'/index.html?class=12&question=g12-ch1-ex1.1-q8');
await page.waitForURL('**/index.html');
assert.equal(await page.locator('#lessonCard').isVisible(),false,'Direct Grade 12 bookmark is unavailable');
console.log('PASS Grade 12 pilot and direct Q8 bookmark return to active Grades 9/10.');
}finally{await browser.close();await app.close();}})().catch(e=>{console.error(e);process.exitCode=1;});
