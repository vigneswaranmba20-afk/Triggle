const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {expression,rich}=require('./g9_math_compiler.cjs');
const compact=s=>expression(s).latex.replace(/\s/g,'');
assert.equal(compact('A={0,3,5,8}'),'A=\\left\\{0,3,5,8\\right\\}');
assert.equal(compact('18∈C'),'18\\inC');assert.equal(compact('6∉A'),'6\\notinA');
assert.equal(compact('∠ABC=90°'),'\\angleABC=90^{\\circ}');
assert.equal(compact('√(x²+y²)'),'\\sqrt{x^{2}+y^{2}}');
assert.equal(compact('sin A = [[∣1−x²∣|1+x²]]'),'\\sinA=\\dfrac{\\left|1-x^{2}\\right|}{1+x^{2}}');
assert.equal(compact('A₁=120 cm²'),'A_{1}=120\\,\\mathrm{cm}^{2}');
assert.equal(compact('P(two heads)=[[1|4]]'),'P\\left(\\text{twoheads}\\right)=\\dfrac{1}{4}');
assert.equal(compact('Σ(x−x̄)=0'),'\\sum\\left(x-\\bar{x}\\right)=0');
assert.equal(compact('12/2 cm'),'\\dfrac{12}{2}\\,\\mathrm{cm}');
assert.throws(()=>expression('10 15 20'),'Data values must not become a product or concatenate');
