'use strict';
// Regenerate the standalone SVG fallbacks from the same plots used by the reader.
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require('playwright');
const { server, launchOptions } = require('./dashboard_test_support.cjs');
const { items } = require('../data/textbook-fidelity/g10-ch5-ex5-1.json');

async function build() {
  const app = await server();
  let browser;
  try {
    browser = await chromium.launch(launchOptions());
    const page = await browser.newPage({ serviceWorkers:'block' });
    await page.goto(app.base+'/index.html?class=10&chapter=g10-ch5');
    for (const item of items.filter(row=>row.figure.asset)) {
      const target = path.join(__dirname,'..',item.figure.asset);
      const original = await fs.readFile(target,'utf8');
      const svg = await page.evaluate(async ({id,original})=>{
        const prior = new DOMParser().parseFromString(original,'image/svg+xml');
        const host = document.createElement('div');
        host.style.cssText = 'position:absolute;left:-2000px;top:0;width:300px;--ver-font:system-ui,sans-serif';
        document.body.append(host);
        window.TriggleCoordinateFigures.mount(host,id,prior.querySelector('desc').textContent,'en');
        const svg = host.querySelector('svg');
        await document.fonts.ready;
        while (!svg.hasAttribute('data-dg-ready')) await new Promise(requestAnimationFrame);

        const scene = svg.cloneNode(true);
        const ns = scene.namespaceURI;
        const {width,height} = svg.viewBox.baseVal;
        const entries = Array.from(host.querySelectorAll('[role="listitem"]'),el=>el.textContent);
        scene.setAttribute('viewBox',`0 0 ${width} ${height+Math.ceil(entries.length/3)*22+10}`);
        scene.setAttribute('font-family','system-ui, sans-serif');
        scene.setAttribute('font-weight','550');
        scene.setAttribute('aria-labelledby','t desc');
        for (const attr of ['class','aria-label','data-dg-ready']) scene.removeAttribute(attr);
        scene.prepend(prior.querySelector('title').cloneNode(true),prior.querySelector('desc').cloneNode(true));
        scene.querySelectorAll('text').forEach(el=>el.setAttribute('font-size','15'));
        entries.forEach((value,index)=>{
          const label = document.createElementNS(ns,'text');
          label.setAttribute('x',String((index%3+.5)*width/3));
          label.setAttribute('y',String(height+15+Math.floor(index/3)*22));
          label.setAttribute('text-anchor','middle');
          label.setAttribute('font-size','14');
          label.setAttribute('fill','#24203c');
          label.textContent = value;
          scene.append(label);
        });
        for (const el of scene.querySelectorAll('line,circle,text,polygon,polyline')) {
          for (const attr of ['x','y','x1','x2','y1','y2','cx','cy','points']) {
            if (el.hasAttribute(attr)) el.setAttribute(attr,el.getAttribute(attr)
              .replace(/-?\d+(?:\.\d+)?/g,number=>String(Math.round(Number(number)*1000)/1000)));
          }
        }
        host.remove();

        const markup = new XMLSerializer().serializeToString(scene);
        let indent = 0;
        const lines = markup.replace(/>(?=<)/g,'>\n').split('\n').map(line=>{
          if (/^<\//.test(line)) indent--;
          const indented = '  '.repeat(indent)+line;
          if (/^<(?:svg|g)\b/.test(line)) indent++;
          return indented;
        });
        return '<!-- Generated by site/tools/build_g10_ch5_coordinate_assets.cjs -->\n'+lines.join('\n')+'\n';
      },{id:item.id,original});
      await fs.writeFile(target,svg);
      console.log(item.figure.asset);
    }
  } finally {
    await browser?.close();
    await app.close();
  }
}

build().catch(error=>{console.error(error);process.exitCode=1;});
