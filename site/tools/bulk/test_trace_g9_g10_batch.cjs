'use strict';
const assert=require('node:assert/strict');
const {assertUnique,scriptsInIndex,registeredIds,batches,buildPlan}=require('./trace_g9_g10_batch.cjs');
assert.throws(()=>assertUnique([{id:'x'},{id:'x'}]),/DUPLICATE_OR_INVALID_CANDIDATE_ID/);
assert.throws(()=>batches([{id:'x'}],21),/INVALID_BATCH_SIZE/);
assert.deepEqual(batches(Array.from({length:25},(_,i)=>({id:'id-'+i}))).map(b=>b.ids.length),[10,10,5]);
const scripts=scriptsInIndex();
assert(scripts.includes('site/data/textbook-exercises/g9-ch1-ex1-2-q1-en.js'));
assert(!scripts.includes('site/data/textbook-exercises/g9-ch1-ex1-2-en.js'),
  'The 34-row staging module must never be treated as live');
