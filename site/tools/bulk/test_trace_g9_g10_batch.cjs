assert(owners.has('g9-ch1-ex1.2-q1-i'));
const plan=buildPlan();
assert.equal(plan.kind,'READ_ONLY_ENGLISH_BATCH_PLAN');
assert.equal(plan.grade9.sourceAuditedCandidateParts,34);
assert.equal(plan.grade9.registeredCandidateIds,9);
assert.equal(plan.grade9.notRegisteredCandidateIds,25);
assert.deepEqual(plan.grade9.queue.map(x=>x.ids.length),[10,10,5]);
assert.equal(plan.grade10.sourceAuditUniqueTasks,21);
assert.equal(plan.grade10.registeredTaskIds,21);
assert.equal(plan.grade10.notRegisteredTaskIds,0);
assert.equal(plan.multipleRegistrations.filter(x=>x.id.startsWith('c10-2-ex2-5-')).length,5);
assert.equal(plan.releaseApproved,false);
assert.equal(plan.externalApiCalls,0);
assert.equal(plan.externalApiCostUsd,0);
assert.equal(plan.grade9.wholeGradeCompletionPercent,null);
assert.equal(plan.grade10.wholeGradeCompletionPercent,null);
assert(plan.grade9.queue.every(b=>b.releaseApproved===false&&b.reviewRequired));
assert(plan.validationRequired.includes('independent mathematics'));
